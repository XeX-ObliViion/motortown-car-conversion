"""NFS dealership (Ara dragstrip lot): dealer spots + map icon for the copied Seoguipo Luxury Cars showroom.

Takes the Seoguipo showroom's own display bays, moves them with the same transform as showroom.txt and gives each one
of our cars (parts from ../spots.txt, so the display car spawns with the right kit). Cars beyond the showroom's bays
continue the last row. Writes spots_nfs.txt for `mappatch clone`.
usage: gen_spots.py [mw]   (mw: the MW dealership beside it, showroom_mw.txt -> spots_mw.txt)
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def transform(name):
    t = {}
    for line in open(os.path.join(HERE, name)):
        f = line.split()
        if f and f[0] in ("pivot", "target"):
            t[f[0]] = [float(v) for v in f[1:]]
    return t["pivot"], t["target"]


# Seoguipo Luxury Cars display bays (Seo-Gui-Po-PremiumDealership spots in Jeju_World): two rows facing each other
BAYS = [
    (9755, 150491, -20890, 155.0), (9544, 150037, -20890, 155.0), (9333, 149584, -20890, 155.0),
    (9121, 149131, -20890, 155.0), (8819, 148720, -20890, 155.0),
    (11703, 149582, -20890, -25.0), (11492, 149129, -20890, -25.0), (11281, 148676, -20890, -25.0),
    (11047, 148233, -20890, -25.0), (10859, 147769, -20890, -25.0),
]
MAP_ICON = (10482, 150661, -20791)   # CarSeller4_2 (Car Dealer, Seoguipo Luxury Cars)
GARAGE = (10371, 152235, -20895, -295.0)   # GarageActorBP3_2: the working garage behind the showroom
DEALERS = {   # tag: (showroom spec, actor prefix, map label, cars, output)
    "nfs": ("showroom.txt", "NFSD", "NFS", ["PS_350Z", "PS_SUPRA", "PS_ELISE", "PS_997TT", "PS_SKYLINE", "PS_SHELBY67",
                                           "PS_CHALLENGER71", "PS_CHEVELLE", "PS_VIPER"], "spots_nfs.txt"),
    "mw": ("showroom_mw.txt", "MWD", "MOST WANTED", ["MW_SUPRA", "MW_VIPER", "MW_ELISE", "MW_M3GTR", "MW_993RWB", "MW_350Z"], "spots_mw.txt"),
}


def main():
    tag = sys.argv[1] if len(sys.argv) > 1 else "nfs"
    showroom, pre, _, CARS, out_name = DEALERS[tag]
    ver = {"nfs": "v4", "mw": "v11"}[tag]   # new name = fresh display car (dealer cars are saved with the world)
    (px, py, pz), (tx, ty, tz, tyaw) = transform(showroom)
    parts = {}
    for line in open(os.path.join(HERE, "..", "spots.txt")):
        f = line.split()
        if len(f) >= 8 and not f[0].startswith("#"):
            parts[f[2]] = f[7]
    for car in CARS:   # cars without a spots.txt line (MW twins): the spec's default parts
        if car not in parts:
            spec = json.load(open(os.path.join(HERE, "..", "..", "cars", car.lower() + ".json")))
            parts[car] = ",".join("%s=%s" % kv for kv in spec["part_overrides"].items())
    bays = list(BAYS)
    while len(bays) < len(CARS):   # continue the last row
        a, b = bays[-2], bays[-1]
        bays.append((2 * b[0] - a[0], 2 * b[1] - a[1], b[2], b[3]))

    def move(x, y, z):
        r = math.radians(tyaw)
        dx, dy = x - px, y - py
        return tx + dx * math.cos(r) - dy * math.sin(r), ty + dx * math.sin(r) + dy * math.cos(r), tz + (z - pz)

    out = ["# generated by gen_spots.py %s: dealership display bays + map icon (Ara dragstrip lot)" % tag]
    for car, (x, y, z, yaw) in zip(CARS, bays):
        nx, ny, nz = move(x, y, z)
        out.append(f"Seo-Gui-Po-PremiumDealership_1  {pre}_{car}_Spot_{ver}  {car}  {nx:.0f}  {ny:.0f}  {nz:.0f}  {yaw + tyaw:.2f}  {parts[car]}")
    # "bay <car> x y z yaw" in the showroom file: a fixed world-space bay (MW: the Diablo SV where the turntable stood)
    for line in open(os.path.join(HERE, showroom)):
        f = line.split()
        if f and f[0] == "bay":
            car = f[1]
            spec = json.load(open(os.path.join(HERE, "..", "..", "cars", car.lower() + ".json")))
            pp = ",".join("%s=%s" % kv for kv in spec["part_overrides"].items())
            out.append(f"Seo-Gui-Po-PremiumDealership_1  {pre}_{car}_Spot_{ver}  {car}  {f[2]}  {f[3]}  {f[4]}  {f[5]}  {pp}")
    ix, iy, iz = move(*MAP_ICON)
    out.append(f"CarSeller4_2  {pre}_MapIcon  -  {ix:.0f}  {iy:.0f}  {iz:.0f}  0")
    gx, gy, gz = move(*GARAGE[:3])
    out.append(f"GarageActorBP3_2  {pre}_Garage  -  {gx:.0f}  {gy:.0f}  {gz:.0f}  {GARAGE[3] + tyaw:.2f}")
    # apron <tile actor> rows N road_z Z side S0 S1: paved ramp of 2.5 m floor-tile copies from the glass front down to
    # the road, for a showroom raised above grassy ground (Ara). Tiles face back (source yaw 65), pivot = front edge
    # corner, so row k's pivot sits 2.5*k m ahead of the front row and the tile pitches up towards the building.
    for line in open(os.path.join(HERE, showroom)):
        f = line.split()
        if not f or f[0] != "apron":
            continue
        tile, rows, road_z, s0, s1 = f[1], int(f[3]), float(f[5]), float(f[7]), float(f[8])
        F0, TZ = 1808.0, -20895.0                      # source front row (local fwd) and tile z
        fa = math.radians(-115.0); fd = (math.cos(fa), math.sin(fa)); rd = (-fd[1], fd[0])
        top = tz + (TZ - pz)                          # tile z in the world
        slope = (top - road_z) / (250.0 * rows)
        pitch = math.degrees(math.atan(slope))
        n = 0
        for k in range(1, rows + 1):
            s = s1
            while s >= s0 - 1:
                wx, wy, _ = move(px + (F0 + 250 * k) * fd[0] + s * rd[0], py + (F0 + 250 * k) * fd[1] + s * rd[1], pz)
                out.append(f"{tile}  {pre}_Apron_{k}_{n}  -  {wx:.0f}  {wy:.0f}  {top - slope * 250 * k:.0f}  {65.0 + tyaw:.2f}  pitch={pitch:.2f}")
                n += 1
                s -= 250
    open(os.path.join(HERE, out_name), "w").write("\n".join(out) + "\n")
    print("\n".join(out[1:]))


if __name__ == "__main__":
    main()
