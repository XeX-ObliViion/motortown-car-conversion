"""NFS dealership (Ara dragstrip lot): dealer spots + map icon for the copied Seoguipo Luxury Cars showroom.

Takes the Seoguipo showroom's own display bays, moves them with the same transform as showroom.txt and gives each one
of our cars (parts from ../spots.txt, so the display car spawns with the right kit). Cars beyond the showroom's bays
continue the last row. Writes spots_nfs.txt for `mappatch clone`.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def transform():
    t = {}
    for line in open(os.path.join(HERE, "showroom.txt")):
        f = line.split()
        if f and f[0] in ("pivot", "target"):
            t[f[0]] = [float(v) for v in f[1:]]
    return t["pivot"], t["target"]


# Seoguipo Luxury Cars display bays (Seo-Gui-Po-PremiumDealership spots in Jeju_World): two rows facing each other
BAYS = [
    (9755, 150491, -20890, 155.0), (9544, 150037, -20890, 155.0), (9333, 149584, -20890, 155.0),
    (9121, 149131, -20890, 155.0), (8819, 148720, -20890, 155.0),
    (11703, 149582, -20890, -25.0), (11492, 149129, -20890, -25.0), (11281, 148676, -20890, -25.0),
    (11047, 148233, -20890, -25.0), (10859, 147769, -20890, -25.0),
]
MAP_ICON = (10482, 150661, -20791)   # CarSeller4_2 (Car Dealer, Seoguipo Luxury Cars)
GARAGE = (10371, 152235, -20895, -295.0)   # GarageActorBP3_2: the working garage behind the showroom
CARS = ["PS_350Z", "PS_SUPRA", "PS_ELISE", "PS_997TT", "PS_SKYLINE", "PS_SHELBY67", "PS_CHALLENGER71",
        "PS_CHEVELLE", "PS_VIPER", "MW_M3GTR", "MW_993RWB"]


def main():
    (px, py, pz), (tx, ty, tz, tyaw) = transform()
    parts = {}
    for line in open(os.path.join(HERE, "..", "spots.txt")):
        f = line.split()
        if len(f) >= 8 and not f[0].startswith("#"):
            parts[f[2]] = f[7]
    bays = list(BAYS)
    while len(bays) < len(CARS):   # continue the last row
        a, b = bays[-2], bays[-1]
        bays.append((2 * b[0] - a[0], 2 * b[1] - a[1], b[2], b[3]))

    def move(x, y, z):
        r = math.radians(tyaw)
        dx, dy = x - px, y - py
        return tx + dx * math.cos(r) - dy * math.sin(r), ty + dx * math.sin(r) + dy * math.cos(r), tz + (z - pz)

    out = ["# generated by gen_spots.py: NFS dealership display bays + map icon (Ara dragstrip lot)"]
    for car, (x, y, z, yaw) in zip(CARS, bays):
        nx, ny, nz = move(x, y, z)
        out.append(f"Seo-Gui-Po-PremiumDealership_1  NFSD_{car}_Spot_v3  {car}  {nx:.0f}  {ny:.0f}  {nz:.0f}  {yaw + tyaw:.2f}  {parts[car]}")
    ix, iy, iz = move(*MAP_ICON)
    out.append(f"CarSeller4_2  NFSD_MapIcon  -  {ix:.0f}  {iy:.0f}  {iz:.0f}  0")
    gx, gy, gz = move(*GARAGE[:3])
    out.append(f"GarageActorBP3_2  NFSD_Garage  -  {gx:.0f}  {gy:.0f}  {gz:.0f}  {GARAGE[3] + tyaw:.2f}")
    open(os.path.join(HERE, "spots_nfs.txt"), "w").write("\n".join(out) + "\n")
    print("\n".join(out[1:]))


if __name__ == "__main__":
    main()
