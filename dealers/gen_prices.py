"""Write the dealer price table for the PSDealerEconomy mod: vehicle blueprint class -> Cost, from every game
Vehicles_* table plus our Vehicles_ProStreet. Lua can't read DataTables safely, so the mod ships this map.
usage: py -3.13 dealers/gen_prices.py <out prices.lua>"""
import glob, json, os, subprocess, sys, tempfile

UAG = os.path.expanduser("~/tools/uassetgui/UAssetGUI.exe")
GAME = os.path.expanduser("~/mt-work/unpacked/MotorTown/Content/DataAsset/Vehicles")
OURS = os.path.expanduser("~/mt-work/build/pak_PS_Common/_work/Vehicles_ProStreet.json")


def rows(js):
    for e in js["Exports"]:
        for r in (e.get("Table") or {}).get("Data", []):
            yield r


def load(uasset):
    out = os.path.join(tempfile.gettempdir(), os.path.basename(uasset) + ".json")
    subprocess.run([UAG, "tojson", uasset.replace("/", "\\"), out.replace("/", "\\"), "VER_UE5_5", "MotorTown"], check=True, cwd=os.path.dirname(UAG))
    return json.load(open(out, encoding="utf-8"))


prices = {}
tables = [load(p) for p in sorted(glob.glob(GAME + "/Vehicles*.uasset"))] + [json.load(open(OURS, encoding="utf-8"))]
for js in tables:
    for r in rows(js):
        v = {p["Name"]: p for p in r["Value"]}
        try:
            cls = v["VehicleClass"]["Value"]["AssetPath"]["AssetName"]
            cost = int(v["Cost"]["Value"])
        except (KeyError, TypeError, ValueError):
            continue
        if cls and cost > 0:
            prices[cls.split(".")[-1]] = cost  # later tables (ours) win, like the game's merge
            prices[r["Name"]] = cost           # the row key too (the buy RPC may pass the vehicle key)
assert len(prices) > 50, "price table too small: %d" % len(prices)
with open(sys.argv[1], "w", encoding="utf-8") as f:
    f.write("-- generated by ps2motortown/dealers/gen_prices.py: vehicle class -> dealer price\nreturn {\n")
    for k in sorted(prices):
        f.write('    ["%s"] = %d,\n' % (k, prices[k]))
    f.write("}\n")
print("%d prices -> %s" % (len(prices), sys.argv[1]))
