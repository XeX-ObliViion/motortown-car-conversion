"""Pack the assets shared by all ProStreet cars into PS_Common_P.pak: the vehicle and part tables (Vehicles_ProStreet,
Wheels_ProStreet), the patched composites (Vehicles, VehicleParts) and the cars' custom engines/gearboxes/torque curves.
They are generated by ONE make_mt_assets.py run over every spec into ~/mt-work/build/pak_PS_Common, so no car pak
overrides another car's tables. Each car's own pak (pack_car.py) takes only its blueprint and meshes.

usage: pack_common.py [--install]"""
import os
import shutil
import subprocess
import sys

REPAK = os.path.expanduser("~/tools/repak/bin/repak.exe")
PAKS = "D:/SteamLibrary/steamapps/common/Motor Town/MotorTown/Content/Paks"
# MT_PLATFORM=WindowsServer: pack from the dedicated-server cook into ~/mt-work/build/server (never installed locally)
PLATFORM = os.environ.get("MT_PLATFORM", "Windows")
BUILD = os.path.expanduser("~/mt-work/build") + ("" if PLATFORM == "Windows" else "/server")
os.makedirs(BUILD, exist_ok=True)
SHARED = ("DataAsset/", "Cars/Parts/Engine/", "Cars/Parts/Transmission/")


def main():
    gen = os.path.join(os.path.expanduser("~/mt-work/build"), "pak_PS_Common" + ("" if PLATFORM == "Windows" else "_server"), "MotorTown", "Content")
    stage = os.path.join(BUILD, "stage_PS_Common_P")
    shutil.rmtree(stage, ignore_errors=True)
    n = 0
    for dirpath, _, files in os.walk(gen):
        if "_work" in dirpath:
            continue
        for f in files:
            rel = os.path.relpath(os.path.join(dirpath, f), gen).replace(os.sep, "/")
            if rel.startswith(SHARED):
                dst = os.path.join(stage, "MotorTown", "Content", rel)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copy2(os.path.join(dirpath, f), dst); n += 1
    # our own engine-sound waves are cooked from the UE project (import_sounds.py), not generated JSON assets
    cooked = "C:/UE/Projects/MotorTown/Saved/Cooked/%s/MotorTown/Content" % PLATFORM
    snd = os.path.join(cooked, "Cars/Parts/Engine/Sound")
    for dirpath, _, files in os.walk(snd):
        for f in files:
            rel = os.path.relpath(os.path.join(dirpath, f), cooked).replace(os.sep, "/")
            if rel.startswith(("Cars/Parts/Engine/Sound/PS_", "Cars/Parts/Engine/Sound/MW_")) and not os.path.basename(f).startswith("SC_"):
                dst = os.path.join(stage, "MotorTown", "Content", rel)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copy2(os.path.join(dirpath, f), dst); n += 1
    out = os.path.join(BUILD, "PS_Common_P.pak")
    subprocess.run([REPAK, "pack", "--version", "V11", stage, out], check=True)
    print("packed %d files -> %s" % (n, out))
    if "--install" in sys.argv and PLATFORM == "Windows":
        shutil.copy2(out, os.path.join(PAKS, os.path.basename(out)))
        print("installed to", PAKS)


if __name__ == "__main__":
    main()
