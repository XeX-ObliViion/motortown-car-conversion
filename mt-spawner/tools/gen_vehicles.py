"""Builds src/vehicles.h (key, display name, category) from the game's Vehicles_* tables (UAssetGUI JSON in ~/mt-work)
and the ProStreet/Most Wanted car specs. Rows the Lua mod finds at runtime but that aren't listed here still show,
under their key. usage: python tools/gen_vehicles.py"""
import glob, json, os, re

HOME = os.path.expanduser("~")
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "vehicles.h")
rows = {}
for path in sorted(glob.glob(os.path.join(HOME, "mt-work", "Vehicles_*.json"))):
    if "ProStreet" in path:
        continue
    for e in json.load(open(path))["Exports"]:
        for r in (e.get("Table") or {}).get("Data", []):
            p = {x["Name"]: x.get("Value") for x in r["Value"]}
            if p.get("bDisabled"):
                continue
            vt = str(p.get("VehicleType") or "Other").split("::")[-1]
            name = re.sub(r"_", " ", r["Name"])
            rows[r["Name"]] = (name, vt, bool(p.get("bHidden")))
for spec in glob.glob(os.path.join(HOME, "OneDrive/Documents/claude/ps2motortown/cars/*.json")):
    if re.search(r"before|corrupt|rims|wings|rim_names", spec):
        continue
    s = json.load(open(spec))
    if "car" in s and "display_name" in s:
        rows[s["car"]] = (s["display_name"], "Modded", False)
cat_order = {"Modded": 0, "Small": 1}
items = sorted(rows.items(), key=lambda kv: (cat_order.get(kv[1][1], 2), kv[1][1], kv[1][0].lower()))
esc = lambda t: t.replace("\\", "\\\\").replace('"', '\\"')
with open(OUT, "w", encoding="utf-8") as f:
    f.write("#pragma once\n// Generated by tools/gen_vehicles.py - do not edit.\n")
    f.write("struct VehicleInfo { const char* key; const char* name; const char* category; bool hidden; };\n")
    f.write("inline const VehicleInfo kVehicles[] = {\n")
    for k, (n, c, h) in items:
        f.write('    {"%s", "%s", "%s", %s},\n' % (esc(k), esc(n), esc(c), "true" if h else "false"))
    f.write("};\n")
print("%d vehicles -> %s" % (len(items), OUT))
from collections import Counter
print(Counter(c for _, (n, c, h) in items))
